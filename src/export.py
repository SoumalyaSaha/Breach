TEMPLATES = {"md": MD_TEMPLATE, "html": HTML_TEMPLATE, "txt": TXT_TEMPLATE}
SUFFIX = {"md": ".md", "html": ".html", "txt": ".txt"}


def _context(state: ProofState) -> dict[str, Any]:
    label = {
        "counterexample_found": "COUNTEREXAMPLE FOUND — the claim is false here",
        "no_counterexample_in_bound": "NO COUNTEREXAMPLE FOUND in the searched bound",
        "unknown": "UNKNOWN — the solver could not decide it",
    }.get(state.verdict, state.verdict)
    ce_block = ""
    if state.counterexample:
        ce_block = "\n".join(f"{k} = {v}" for k, v in state.counterexample.items())
    return {
        "claim": state.claim,
        "verdict_label": label,
        "counterexample": state.counterexample,
        "counterexample_block": ce_block,
        "scope_note": state.scope_note,
        "symbolic_form": state.symbolic_form,
        "steps": [
            {
                "id": s.id,
                "text": s.text,
                "status": s.status,
                "challenge_text": s.challenge_text,
                "agent_response": s.agent_response,
                "implicated": s.implicated,
                "missing_assumption": s.missing_assumption,
            }
            for s in state.steps
        ],
        "diagnosis": state.diagnosis,
        "extra_constraints": state.extra_constraints,
        "search_certificate": state.search_certificate,
        "citations": [c.to_dict() for c in state.citations],
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
    }


def suggest_filename(state: ProofState, format: str = "md") -> str:
    """The file name Breach uses for this session and format."""
    fmt = (format or "md").lower().lstrip(".")
    stamp = time.strftime("%Y%m%d-%H%M%S")
    slug = "".join(ch if ch.isalnum() else "-" for ch in state.claim[:28]).strip("-").lower()
    digest = hashlib.sha256(state.claim.encode("utf-8")).hexdigest()[:6]
    return f"breach-{slug or 'report'}-{digest}-{stamp}{SUFFIX.get(fmt, '.md')}"


def render_proof(state: ProofState, format: str = "md") -> str:
    """Render the report as text (no file written)."""
    fmt = (format or "md").lower().lstrip(".")
    if fmt not in TEMPLATES:
        raise ValueError(f"unsupported export format: {format!r} (use md, html or txt)")
    return Template(TEMPLATES[fmt]).render(**_context(state))


def export_proof(
    state: ProofState,
    format: str = "md",
    output_dir: Optional[str] = None,
) -> str:
    """Render the proof state and write it to `outputs/`. Returns the path."""
    fmt = (format or "md").lower().lstrip(".")
    if fmt not in TEMPLATES:
        raise ValueError(f"unsupported export format: {format!r} (use md, html or txt)")
    out_dir = output_dir or OUTPUT_DIR
    os.makedirs(out_dir, exist_ok=True)
    filename = suggest_filename(state, fmt)
    path = os.path.join(out_dir, filename)
    rendered = render_proof(state, fmt)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(rendered)
    return os.path.abspath(path)
